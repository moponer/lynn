/**
 * 流式输出调参常量（2026-11-19 修 消息#11）。
 *
 * ## 为什么单独一个文件
 *
 * 这个值主进程与渲染层都要用。放在 `contract.ts` 里当然也行，但那是"IPC 契约"，
 * 混进调参常量会让契约文件越来越杂；单独一页更清楚，也便于将来加别的流式参数。
 *
 * ## 为什么必须单一来源
 *
 * 此前这个意图散落在三个魔数里：
 *  - 主进程直连路径：16ms（约 60fps）
 *  - 主进程 RPC 路径：80ms（硬编码）
 *  - 渲染层合并窗口：80ms
 *
 * 两条模型路径的推送频率差 5 倍，而渲染层本来就按 80ms 合并显示——16ms 那一路
 * 推出去的绝大多数帧会被直接丢掉，纯浪费主进程 CPU。
 *
 * 统一到 80ms 后：三条路径行为一致，不再随"走了哪条模型路径"漂移。
 */
export const DELTA_FRAME_MIN_GAP_MS = 80;
