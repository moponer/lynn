/**
 * 飞书 open_id 校验（2026-11-18 P16-2）。
 *
 * 单独一个文件的原因：它同时被**内核**（保存配置时校验）和**渠道适配层**
 * （启动前校验）用到。放进任何一边都会让另一边产生方向不对的依赖
 * ——内核不该为了一个纯函数去 import 渠道实现。
 *
 * ## 为什么必须有校验（真实事故）
 *
 * 用户从飞书后台复制 open_id 时多选了末尾 3 个字符（`ou_xxx...ccs`，
 * 38 字符而非标准 35 字符）。保存成功、渠道起来了，但每条消息都被白名单
 * 挡掉，表现为"发消息完全没反应"——很难自己看出是 id 写错了。
 */

/**
 * 合法格式：`ou_` + 32 位十六进制（共 35 字符）。
 *
 * 前后空白被容忍（用户粘贴时常带空格），中间不允许。
 */
export function isValidOpenId(id: string): boolean {
  return /^ou_[0-9a-f]{32}$/i.test(String(id ?? "").trim());
}